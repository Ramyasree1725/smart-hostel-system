/**
 * Retrieves all fee ledger records from this static dataset.
 * @returns {Array<Object>} Array of fee transaction objects.
 */
function getAll() {
  return staticFeeLedger01;
}

/**
 * Finds all fee transactions associated with a specific student ID.
 * @param {string} studentId - Unique identifier of the student.
 * @returns {Array<Object>} Filtered array of transaction objects.
 */
function findByStudentId(studentId) {
  if (!studentId || typeof studentId !== 'string') {
    return [];
  }
  return staticFeeLedger01.filter(
    (record) => record.studentId.toLowerCase() === studentId.trim().toLowerCase()
  );
}

/**
 * Filters fee records based on payment status.
 * @param {string} status - Status to filter by (e.g., 'Paid', 'Partial', 'Overdue', 'Pending').
 * @returns {Array<Object>} Matching fee transaction records.
 */
function filterByStatus(status) {
  if (!status || typeof status !== 'string') {
    return [];
  }
  return staticFeeLedger01.filter(
    (record) => record.paymentStatus.toLowerCase() === status.trim().toLowerCase()
  );
}

/**
 * Calculates aggregated financial statistics for the dataset batch.
 * @returns {Object} Financial summary object containing total billed, collected, outstanding, and count.
 */
function getLedgerSummary() {
  return staticFeeLedger01.reduce(
    (summary, item) => {
      summary.totalInvoicedINR += item.totalInvoiceAmountINR;
      summary.totalCollectedINR += item.amountPaidINR;
      summary.totalOutstandingINR += item.balanceAmountINR;
      summary.totalPenaltiesINR += item.penaltyAmountINR;
      summary.totalDiscountsINR += item.discountAmountINR;
      summary.recordCount += 1;
      return summary;
    },
    {
      totalInvoicedINR: 0,
      totalCollectedINR: 0,
      totalOutstandingINR: 0,
      totalPenaltiesINR: 0,
      totalDiscountsINR: 0,
      recordCount: 0
    }
  );
}

